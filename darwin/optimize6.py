def main():
    changed = 0
    for slug, steps in STEPS.items():
        p = SKILLS / slug / "SKILL.md"
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8")
        if "### 执行步骤" in text:
            continue
        lines = ["\n### 执行步骤\n", "| # | 步骤 | 输入 | 输出 |", "|---|---|---|---|"]
        for i, (name, inp, out) in enumerate(steps, 1):
            lines.append(f"| {i} | {name} | {inp} | {out} |")
        block = "\n".join(lines) + "\n"
        if "### 失败分支（if-then）" in text:
            text = text.replace("### 失败分支（if-then）", block + "\n### 失败分支（if-then）", 1)
        elif "## B — 边界" in text:
            text = text.replace("## B — 边界", block + "\n## B — 边界", 1)
        else:
            text = text.rstrip() + "\n" + block
        p.write_text(text, encoding="utf-8")
        changed += 1
    print(f"round 6: {changed} skills updated")


